"""
Pydantic schemas for LangChain structured output parsing.
"""
from typing import List, Optional
from pydantic import BaseModel, Field


class InteractionExtraction(BaseModel):
    """
    Extracted data from a natural language interaction log provided by a field rep.
    This structure maps closely to the Django Interaction model.
    """
    
    hcp_name: Optional[str] = Field(
        default=None,
        description="The name of the Healthcare Professional mentioned in the log (e.g., 'Dr. Sharma'). Null if not mentioned."
    )
    
    interaction_type: str = Field(
        default="in_person",
        description="The type of interaction. Must be one of: 'in_person', 'phone', 'email', 'virtual', 'event'. Defaults to 'in_person'."
    )
    
    date: Optional[str] = Field(
        default=None,
        description="The date of the interaction in YYYY-MM-DD format. If not explicitly mentioned, assume None (today's date will be used by the system)."
    )
    
    notes: str = Field(
        default="",
        description="The raw notes or a polished version of what the representative entered."
    )
    
    products_discussed: List[str] = Field(
        default_factory=list,
        description="A list of specific medical products, drugs, or devices discussed during the interaction."
    )
    
    follow_up_required: bool = Field(
        default=False,
        description="True if the representative mentioned needing to follow up, send materials, or meet again."
    )
    
    follow_up_date: Optional[str] = Field(
        default=None,
        description="The date for the follow-up in YYYY-MM-DD format, if mentioned."
    )
    
    ai_summary: str = Field(
        default="",
        description="A brief 1-2 sentence summary of the interaction generated by the AI."
    )
    
    ai_sentiment: str = Field(
        default="neutral",
        description="The sentiment of the interaction. Must be one of: 'positive', 'neutral', 'negative'."
    )
